// Copies the desktop contract from the Chatter client into apps/desktop/src/contract.
// The client owns these types; the desktop app type-checks its bridge against
// them. `--check` fails instead of writing when the copies are out of date.
//
//   node scripts/sync-contract.mjs [--check]   (CHATTER_DIR defaults to ../Chatter)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const chatter = resolve(process.env.CHATTER_DIR ?? resolve(here, "../../Chatter"));
const out = resolve(here, "../apps/desktop/src/contract");
const check = process.argv.includes("--check");

const header = (from) =>
  `// GENERATED by scripts/sync-contract.mjs from Chatter ${from} — do not edit here.\n\n`;

const files = [
  {
    from: "client/src/lib/desktop/bridge.ts",
    to: "bridge.ts",
    transform: (s) => s,
  },
  {
    from: "client/src/lib/media/types.ts",
    to: "media.ts",
    // The client imports this from a hook; inline it so the copy stands alone.
    transform: (s) =>
      s.replace(
        /import type \{ NoiseSuppressionMode \} from "@\/hooks\/useVoiceSettings";/,
        'export type NoiseSuppressionMode = "none" | "browser" | "rnnoise";',
      ),
  },
];

if (!existsSync(resolve(chatter, files[0].from))) {
  console.log(`no Chatter checkout at ${chatter}; skipping`);
  process.exit(0);
}

let stale = false;
for (const f of files) {
  const next = header(f.from) + f.transform(readFileSync(resolve(chatter, f.from), "utf8").replace(/\r\n/g, "\n"));
  const target = resolve(out, f.to);
  const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current === next) continue;
  if (check) {
    console.error(`${f.to} is out of date with ${f.from}; run node scripts/sync-contract.mjs`);
    stale = true;
  } else {
    writeFileSync(target, next);
    console.log(`updated ${f.to}`);
  }
}
process.exit(stale ? 1 : 0);
